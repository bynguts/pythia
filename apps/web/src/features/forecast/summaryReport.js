// HTML body of the exported executive-summary PDF (ReportActions.jsx). Pure, so the
// e2e suite can check the wording without rendering a PDF.

const fmt = (value) => (Number.isFinite(Number(value)) ? Number(value).toLocaleString("en-GB") : "–");

// The queue figures are a seeded simulation against a stated current-practice
// baseline (departure SD, assumed) with a sensitivity band, never "all trucks at peak".
export function queueImpactHtml(impact) {
  if (!impact || impact.baseline_wait_minutes === undefined) return "";
  const metric = impact.minutes_per_truck || {};
  const sd = metric.baseline_departure_sd_minutes;
  const band = metric.sensitivity?.baseline_band;
  const sds = metric.assumptions?.sensitivity_departure_sd_minutes || [];
  const bandText =
    Array.isArray(band) && band.length === 2
      ? ` · band <b>${fmt(band[0])}–${fmt(band[1])} min</b>` +
        (sds.length ? ` across SD ${fmt(sds[0])}–${fmt(sds.at(-1))} min` : "")
      : "";
  const label = impact.classification || "SIMULATED";
  return `
      <h2>Queue Optimization Impact (Case 1) — ${label}</h2>
      <p>Current-practice baseline (departures SD ${fmt(sd)} min, assumed): <b>${fmt(impact.baseline_wait_minutes)} min</b> mean wait (p95 ${fmt(impact.baseline_p95_minutes)} min)${bandText} · staggered <b>${fmt(impact.optimized_wait_minutes)} min</b> (p95 ${fmt(impact.optimized_p95_minutes)} min)</p>
      <p>Queue wait reduction against the assumed baseline: <b>-${fmt(impact.queue_reduction_percent)}%</b> (${impact.method}; ${label}, not a weighbridge measurement)</p>
      `;
}

export function buildSummaryReportHtml(data) {
  const hotspots = Array.isArray(data.top_hotspots) ? data.top_hotspots : [];
  const hotspotRows = hotspots
    .map(
      (h) => `
      <tr>
        <td>${h.kecamatan}</td><td>${h.city}</td>
        <td>${h.predicted_tons} t/day</td><td>${h.trucks_required}</td>
        <td>${h.crews_required}</td><td>${h.man_hours_required}</td>
      </tr>`,
    )
    .join("");
  const hotspotsHtml = hotspotRows
    ? `
      <h2>Predicted Hotspots &amp; Resource Readiness (Case 2) — MODEL OUTPUT</h2>
      <table border="1" cellspacing="0" cellpadding="4" style="border-collapse:collapse;font-size:12px;">
        <thead><tr><th>District</th><th>City</th><th>Forecast</th><th>Trucks</th><th>Crews</th><th>Man-hours</th></tr></thead>
        <tbody>${hotspotRows}</tbody>
      </table>`
    : "";
  const fs = data.fleet_status || {};
  const activityLine = fs.by_activity
    ? Object.entries(fs.by_activity)
        .map(([k, v]) => `${k.replaceAll("_", " ")}: ${v}`)
        .join(" · ")
    : "";
  const fleetHtml = fs.total_trucks
    ? `
      <h2>Fleet Condition (Case 1) — SIMULATED fleet</h2>
      <p><b>${fs.total_trucks} units</b> tracked — ${fs.damaged_count} with open damage status.</p>
      <p>Activity: ${activityLine}</p>
      `
    : "";
  const gap = data.facility_summary || {};
  const gapHtml = gap.kecamatan_total
    ? `
      <h2>Facility Gap Analysis (Case 2)</h2>
      <p>${gap.critical_count} critical districts · total gap <b>${gap.total_gap_ton_per_day} t/day</b> ·
      +${gap.total_extra_trucks_needed} trips/day recommended · ${gap.total_new_tps_sites_needed} new TPS sites (bounded share).</p>
      `
    : "";
  return `
      <h1>Pythia Executive Summary</h1>
      <p class="pdf-date">Generated by Pythia</p>
      <p>${data.summary}</p>
      ${queueImpactHtml(data.queue_impact)}
      ${fleetHtml}
      ${hotspotsHtml}
      ${gapHtml}
      <h2>Audit &amp; Evidence Trail</h2>
      <ul>
        <li>AI route deviation detection (Isolation Forest + corridor geometry) with follow-up trail (OPEN &rarr; DISPATCHED &rarr; RESOLVED)</li>
        <li>Permit-compliant A* rerouting with computed alternative corridors (JORR bypass, coastal toll)</li>
        <li>Monthly landfill-intake forecast backtested on real Bantargebang data against the strongest simple baseline, 1–3 months ahead of its last observed month (see Data &amp; ML Audit); daily per-district forecasts are calibrated-synthetic and carry no accuracy claim</li>
        <li>Field dispatch loop with driver confirmation and offline sync</li>
      </ul>
      <p style="font-size:11px;color:#666;">${data.model_suitability_note || ""}</p>
    `;
}
